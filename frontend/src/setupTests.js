import '@testing-library/jest-dom';

// The test environment (jsdom) has no window.matchMedia, but react-hot-toast
// uses it to check the "reduce motion" setting. Provide a minimal stand-in.
window.matchMedia =
  window.matchMedia ||
  ((query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }));
